const interpolate = (value, variables = {}) => value.replace(/\{(\w+)\}/g, (_, key) => variables[key] ?? '');

export const getUiLanguage = () => {
  const language = useSettingsStore.getState().uiLanguage;
  return language === 'en' ? 'en' : 'es';
};

export const translate = (key, variables = {}, language = getUiLanguage()) => {
  const value = messages[language]?.[key] ?? messages.es[key] ?? key;
  return interpolate(value, variables);
};

export const translateCourseError = (error, language = getUiLanguage()) => {
  const message = error?.message || String(error || '');
  if (message.includes('URL no reconocida')) return translate('courseError.invalidUrl', {}, language);
  if (message.includes('firewall')) return translate('courseError.firewall', {}, language);
  if (message.includes('No se encontraron clases')) return translate('courseError.noClasses', {}, language);
  if (message.includes('Curso no accesible')) return translate('courseError.requiresAuth', {}, language);
  if (message.includes('Curso no encontrado')) return translate('courseError.notFound', {}, language);
  if (message.includes('Acceso denegado')) return translate('courseError.forbidden', {}, language);

  const status = message.match(/Error (\d+)/)?.[1];
  if (status) return translate('courseError.status', { status }, language);
  return message || translate('courseError.generic', {}, language);
};

export const useI18n = () => {
  const language = useSettingsStore(state => state.uiLanguage === 'en' ? 'en' : 'es');
  return { language, t: (key, variables) => translate(key, variables, language) };
};
